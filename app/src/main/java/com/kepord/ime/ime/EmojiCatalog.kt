    private var cachedCategories: List<EmojiCategory>? = null

    fun getCategories(recentEmojis: List<String>): List<EmojiCategory> {
        val base = cachedCategories ?: buildAndFilterCategories().also { cachedCategories = it }
        val recentCat = EmojiCategory(
            id = "recent",
            titleAr = "الأخيرة",
            icon = "🕒",
            emojis = if (recentEmojis.isNotEmpty()) recentEmojis else defaultRecent
        )
        return listOf(recentCat) + base
    }

    private fun buildAndFilterCategories(): List<EmojiCategory> {
        val paint = Paint()
        fun filterSupported(raw: List<String>): List<String> {
            return raw.filter { emoji ->
                if (emoji.codePointCount(0, emoji.length) == 1) {
                    paint.hasGlyph(emoji)
                } else {
                    true
                }
            }
        }

        return listOf(
            EmojiCategory("smileys", "الوجوه", "😀", filterSupported(smileys)),
            EmojiCategory("people", "الأيدي والناس", "👋", filterSupported(peopleAndHands)),
